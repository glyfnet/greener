/**
 * `npm run build:index` — build everything the Worker ships with (FR-45, D-06).
 *
 * Writes `server/src/generated/`:
 * - kb-index.json        BM25 index of the global KB (Section 7.4)
 * - question-bank.json   validated `data/question-bank.yaml`
 * - cost-reference.json  validated `data/cost-reference.csv`
 * - declared-weeds.json  validated `data/declared-weeds.csv`
 * - native-nurseries.json validated `data/native-nurseries.csv`
 * - species-images.json  validated `data/species-images.csv` (D-23)
 * - intake-card.ts       the question card HTML with its script inlined
 *
 * Heavy work happens here, not at request time (D-10).
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import ts from "typescript";
import { buildIndex, type IndexedChunk } from "../server/src/rag/bm25.js";
import { chunkMarkdown } from "../server/src/rag/chunk.js";
import { manifestRuleErrors } from "../server/src/rag/manifest.js";
import { parseCostReference } from "../server/src/core/cost.js";
import { parseNurseries } from "../server/src/core/nurseries.js";
import { parseSpeciesImages } from "../server/src/core/images.js";
import { fail, loadManifest, loadQuestionBank, parseDeclaredWeeds, path, readText } from "./lib.js";

const OUT = path("server/src/generated");

function write(name: string, content: string): void {
  writeFileSync(`${OUT}/${name}`, content);
  console.log(`  wrote server/src/generated/${name} (${(content.length / 1024).toFixed(1)} KB)`);
}

function buildKb(): string {
  const manifest = loadManifest();
  const errors = manifestRuleErrors(manifest);
  if (errors.length) fail(`kb/manifest.yaml has errors:\n  ${errors.join("\n  ")}`);
  const chunks: IndexedChunk[] = [];
  for (const item of manifest.items) {
    const base = { itemId: item.id, title: item.title, tier: item.tier, url: item.sourceUrl, publisher: item.publisher, licence: item.licence, region: item.region, dateChecked: item.dateChecked, tags: item.tags, accessLevel: "public" as const };
    if (item.tier === "open_content") {
      const file = `kb/sources/${item.file}`;
      if (!existsSync(path(file))) fail(`${item.id}: ${file} does not exist`);
      chunkMarkdown(readText(file)).forEach((c, i) => chunks.push({ ...base, chunkId: `kb:${item.id}#${i + 1}`, heading: c.heading, text: c.text }));
    } else {
      // Link catalogue: index the summary and tags only (D-15).
      chunks.push({ ...base, chunkId: `kb:${item.id}`, heading: "Summary", text: item.summary.trim() });
    }
  }
  const builtAt = new Date().toISOString().slice(0, 10);
  const index = buildIndex(chunks, builtAt);
  console.log(`  indexed ${manifest.items.length} KB items as ${chunks.length} chunks`);
  return JSON.stringify(index);
}

function buildCard(): string {
  const source = readText("server/ui/intake-card/card.ts");
  const out = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.None, removeComments: true } });
  const js = out.outputText.replace(/^"use strict";\s*/, "").replace(/export \{\};\s*$/, "");
  const html = readText("server/ui/intake-card/card.html");
  if (!html.includes("/*CARD_SCRIPT*/")) fail("card.html is missing the /*CARD_SCRIPT*/ placeholder");
  // Guard against a script that would close the <script> tag early.
  if (/<\/script/i.test(js)) fail("card.ts must not contain '</script'");
  const page = html.replace("/*CARD_SCRIPT*/", () => js);
  // The card's address changes with its content: hosts cache a UI resource by
  // its URI, so an unchanged URI kept serving an old card after a deploy.
  const version = createHash("sha256").update(page).digest("hex").slice(0, 12);
  return `// Generated by scripts/build-index.ts from server/ui/intake-card. Do not edit.\nexport const INTAKE_CARD_VERSION = ${JSON.stringify(version)};\nexport const INTAKE_CARD_HTML = ${JSON.stringify(page)};\n`;
}

console.log("Building server data…");
mkdirSync(OUT, { recursive: true });
write("kb-index.json", buildKb());
write("question-bank.json", JSON.stringify(loadQuestionBank()));
try {
  write("cost-reference.json", JSON.stringify(parseCostReference(readText("data/cost-reference.csv"))));
  write("declared-weeds.json", JSON.stringify(parseDeclaredWeeds(readText("data/declared-weeds.csv"))));
  write("native-nurseries.json", JSON.stringify(parseNurseries(readText("data/native-nurseries.csv"))));
  write("species-images.json", JSON.stringify(parseSpeciesImages(readText("data/species-images.csv"))));
} catch (e) {
  fail(e instanceof Error ? e.message : String(e));
}
write("intake-card.ts", buildCard());
console.log("✓ build:index done");
